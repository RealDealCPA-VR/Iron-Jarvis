def read_lf(path: Path) -> str:
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def write_lf(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.replace("\r\n", "\n").encode("utf-8"))


def area_files() -> list[Path]:
    return sorted(p for p in RULES_DIR.glob("*.md") if not NOT_AREAS.match(p.name))


def _flat(text: str, limit: int = 1500) -> str:
    return re.sub(r"\s+", " ", text[:limit]).strip()


def entry_headline(block: str) -> str:
    """One line for the contents list, from a rule's own first words."""
    if block.startswith("### "):
        return block.split("\n", 1)[0][4:].strip()
    flat = _flat(block[2:])
    m = re.match(r"\*\*(.+?)\*\*", flat)
    head = m.group(1).strip() if m else flat[:110].strip().rstrip(".,;:") + "…"
    ver = re.search(r"\bv(1\.\d+\.\d+)", flat[:700])
    return f"**{head}**" + (f" (v{ver.group(1)})" if ver else "") if m else head


def with_contents(text: str) -> str:
    """The area file's text with its contents list rebuilt. Pure."""
    lines = text.split("\n")
    try:
        a = lines.index(INDEX_START)
        b = lines.index(INDEX_END)
        r = lines.index(RULES_HEADING)
    except ValueError as exc:
        raise SystemExit(f"an area file lacks a marker line: {exc}") from None
    if not a < b < r:
        raise SystemExit("an area file's marker lines are out of order")
    head, tail = lines[: a + 1], lines[b:]
    # Entries: every line under "## Rules" that starts a top-level bullet or a
    # "### " block. Offsets are counted from the INDEX_END line.
    starts = [
        i for i in range(r - b + 1, len(tail))
        if tail[i].startswith("- ") or tail[i].startswith("### ")
    ]
    entries = []
    for n, i in enumerate(starts):
        end = starts[n + 1] if n + 1 < len(starts) else len(tail)
        entries.append((i, entry_headline("\n".join(tail[i:end]))))
    body_lines = 2 + len(entries)  # heading, blank line, one line per entry
    first_line = len(head) + body_lines + 1  # 1-based number of tail[0]
    body = [f"## Contents ({len(entries)} entries; the number is the line where the full text starts)", ""]
    body += [f"- L{first_line + i}: {text_}" for i, text_ in entries]
    return "\n".join(head + body + tail)


def area_title(path: Path) -> str:
    first = read_lf(path).split("\n", 1)[0]
    return first[len("# Rules: "):] if first.startswith("# Rules: ") else path.stem


def pointer_text(what: str, rows: list[tuple[str, str]]) -> str:
    out = [
        GENERATED,
        f"# Rules for {what}",
        "",
        "Before you change a file here, open the rules file for its part of the code, read",
        "the contents list at its top, then read the entries your change touches. The rules",
        "for every change are in the root `CLAUDE.md`.",
        "",
        "| Code | Rules |",
        "|---|---|",
    ]
    out += [f"| {code} | `docs/rules/{area}.md` |" for code, area in rows]
    return "\n".join(out) + "\n"


def src_pointer() -> str:
    rows: list[tuple[str, str]] = []
    for area in sorted(PACKAGE_AREAS):
        names = [n for n in PACKAGE_AREAS[area] if n not in {"daemon", "core"}]
        if names:
            rows.append((", ".join(f"`{n}{'' if n.endswith('.py') else '/'}`" for n in names), area))
    rows += SPLIT_PACKAGES
    text = pointer_text("the daemon (`src/iron_jarvis/`)", rows)
    return text.replace("| Code | Rules |", "| Code (under `src/iron_jarvis/`) | Rules |")


def outputs() -> dict[Path, str]:
    """Every generated file and the text it should hold."""
    out: dict[Path, str] = {}
    for path in area_files():
        out[path] = with_contents(read_lf(path))
    out[ROOT / "src" / "CLAUDE.md"] = src_pointer()
    for rel, (what, rows) in POINTERS.items():
        out[ROOT / rel] = pointer_text(what, rows)
    return out


def problems() -> list[str]:
    """Everything that is out of step. Empty = all good."""
    bad: list[str] = []
    areas = {p.stem for p in area_files()}

    for path, want in outputs().items():
        have = read_lf(path) if path.exists() else None
        if have != want:
            bad.append(f"{path.relative_to(ROOT).as_posix()}: out of date (run scripts/gen_agent_rules.py)")

    # Every area a table names must exist.
    named = set(PACKAGE_AREAS) | {a for _, a in SPLIT_PACKAGES}
    named |= {a for _, rows in POINTERS.values() for _, a in rows}
    for a in sorted(named - areas):
        bad.append(f"a table in gen_agent_rules.py names docs/rules/{a}.md, which does not exist")

    # Every package belongs to an area.
    claimed = [n for names in PACKAGE_AREAS.values() for n in names]
    for n in sorted({n for n in claimed if claimed.count(n) > 1}):
        bad.append(f"PACKAGE_AREAS lists {n!r} under two areas")
    pkg_root = ROOT / "src" / "iron_jarvis"
    on_disk = {
        p.name for p in pkg_root.iterdir()
        if p.name not in NOT_CODE and (p.is_dir() or p.suffix == ".py")
    }
    for n in sorted(on_disk - set(claimed)):
        bad.append(f"src/iron_jarvis/{n} belongs to no area: add it to PACKAGE_AREAS in scripts/gen_agent_rules.py")
    for n in sorted(set(claimed) - on_disk):
        bad.append(f"PACKAGE_AREAS names {n!r}, which is not under src/iron_jarvis/")

    # The root file: short, no history, and it names every area file.
    root = read_lf(ROOT_FILE)
    n_lines = len(root.rstrip("\n").split("\n"))
    if n_lines > ROOT_MAX_LINES:
        bad.append(f"CLAUDE.md has {n_lines} lines; the limit is {ROOT_MAX_LINES} (move a rule to its area file)")
    for m in sorted(set(re.findall(r"\bv1\.\d+\.\d+\b", root))):
        bad.append(f"CLAUDE.md names the version {m}: history belongs in the area file, not here")
    in_root = set(re.findall(r"docs/rules/([a-z-]+)\.md", root))
    for a in sorted(areas - in_root):
        bad.append(f"CLAUDE.md does not name docs/rules/{a}.md")
    for a in sorted(in_root - areas):
        bad.append(f"CLAUDE.md names docs/rules/{a}.md, which does not exist")
    return bad


def main(argv: list[str]) -> int:
    if "--check" in argv:
        bad = problems()
        for line in bad:
            print(line)
        print("agent rules: " + ("OUT OF STEP" if bad else "in step"))
        return 1 if bad else 0
    for path, text in outputs().items():
        write_lf(path, text)
    print(f"wrote {len(outputs())} files")
    return 0


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main(sys.argv[1:]))
