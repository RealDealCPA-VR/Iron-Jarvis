"""Keep the agent rule files in step: contents lists, folder pointers, limits.

The rules agents work by live in three places:

* the root ``CLAUDE.md``: the short file every session loads (rules for EVERY change);
* ``docs/rules/<area>.md``: the full rules for one area of the code;
* a small ``CLAUDE.md`` in each top-level code folder that names the area files
  for the code under it (an agent tool loads it when it reads a file there).

This script writes the generated parts and checks the limits:

    uv run python scripts/gen_agent_rules.py           # write
    uv run python scripts/gen_agent_rules.py --check   # exit 1 if anything is out of step

What it writes
--------------
1. In every area file, the "Contents" list between the two marker lines: one
   line per rule, with the line number where its full text starts.
2. The folder pointer files (``POINTERS`` below).

What ``--check`` also refuses
-----------------------------
* a root ``CLAUDE.md`` longer than ``ROOT_MAX_LINES`` or naming a version number;
* an area file the root file does not name, or a named file that does not exist;
* a package under ``src/iron_jarvis/`` that no area claims (``PACKAGE_AREAS``).

Stdlib only. All output is UTF-8 with LF line ends.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RULES_DIR = ROOT / "docs" / "rules"
ROOT_FILE = ROOT / "CLAUDE.md"
ROOT_MAX_LINES = 300

INDEX_START = "<!-- contents:start (generated by scripts/gen_agent_rules.py; do not edit) -->"
INDEX_END = "<!-- contents:end -->"
RULES_HEADING = "## Rules"
GENERATED = "<!-- Generated by scripts/gen_agent_rules.py. Edit the table there, not this file. -->"

#: Files in docs/rules/ that are not area files.
NOT_AREAS = re.compile(r"^(ARCHIVE-|SPLIT-RECORD-|README)")

# ---------------------------------------------------------------------------
