"""Write the closing-offer reading's PATTERNS into the dashboard's twin
(v1.406.0 part 4, the next-step box).

``src/iron_jarvis/harness/closing_offer.py`` reads a reply's last sentence
(does it offer more work, and is that work the user's to decide?). The
dashboard's next-step box reads the SAME sentence of a saved reply, so its
twin ``dashboard/lib/closingOffer.ts`` must use the same patterns. They are
copied here from the compiled Python patterns, never typed twice: this script
rewrites the block between ``// closing-offer-patterns:start`` and
``// closing-offer-patterns:end``.

    uv run python scripts/gen_closing_offer_ts.py          # rewrite the block
    uv run python scripts/gen_closing_offer_ts.py --check  # exit 1 when stale

``tests/test_closing_offer_twin_v1406.py`` runs ``--check`` and holds the two
readings equal on every table row of ``tests/test_closing_offer_v1402.py``.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TS = ROOT / "dashboard" / "lib" / "closingOffer.ts"
START = "// closing-offer-patterns:start"
END = "// closing-offer-patterns:end"

#: The TS key → the Python module's compiled pattern name.
NAMES = {
    "fence": "_FENCE_RX",
    "quote": "_QUOTE_RX",
    "leadMark": "_LEAD_MARK_RX",
    "emphasis": "_EMPHASIS_RX",
    "sentenceSplit": "_SENTENCE_SPLIT_RX",
    "asks": "_ASKS",
    "states": "_STATES",
    "canIf": "_CAN_IF",
    "explain": "_EXPLAIN_RX",
    "vague": "_VAGUE_RX",
    "later": "_LATER_RX",
    "actionLead": "_ACTION_LEAD_RX",
    "actionFiller": "_ACTION_FILLER_RX",
    "userOwns": "_USER_OWNS_RX",
    "production": "_PRODUCTION_RX",
    "explainStart": "_EXPLAIN_START_RX",
    "declineAlt": "_DECLINE_ALT_RX",
    "actionEnd": "_ACTION_END_RX",
}


def block() -> str:
    sys.path.insert(0, str(ROOT / "src"))
    from iron_jarvis.harness import closing_offer as co

    lines = [START, "// GENERATED by scripts/gen_closing_offer_ts.py from harness/closing_offer.py — do not edit.",
             "export const PATTERNS: Readonly<Record<string, { source: string; flags: string }>> = {"]
    for key, name in NAMES.items():
        rx = getattr(co, name)
        flags = "i" if rx.flags & re.IGNORECASE else ""
        lines.append(f"  {key}: {{ source: {json.dumps(rx.pattern, ensure_ascii=False)}, flags: {json.dumps(flags)} }},")
    lines.append("};")
    lines.append(f"export const OFFER_ACTION_MAX = {co.OFFER_ACTION_MAX};")
    lines.append(END)
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = TS.read_bytes().decode("utf-8").replace("\r\n", "\n")
    a, b = text.index(START), text.index(END) + len(END)
    new = text[:a] + block() + text[b:]
    if "--check" in argv:
        if new != text:
            print(f"{TS} is stale: run uv run python scripts/gen_closing_offer_ts.py")
            return 1
        return 0
    TS.write_bytes(new.encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
