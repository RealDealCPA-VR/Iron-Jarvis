"""Write the subscription-CLI table into the dashboard's twin (v1.426.0,
Wave 6 lane B, E5).

``src/iron_jarvis/providers/subscription_clis.py`` is THE table of the CLIs a
person signs in to (Claude Code, Codex, the Grok CLI): provider id, vendor
word, Iron-Proxy provider, home variable, Build › Code harness, binary,
names. The dashboard needs the same facts (the Iron-Proxy card's fallback
provider map, the plain provider names), so ``dashboard/lib/subscriptionClis.ts``
is GENERATED from it — never typed twice:

    uv run python scripts/gen_subscription_clis.py          # write the twin
    uv run python scripts/gen_subscription_clis.py --check  # exit 1 when stale

``tests/test_subscription_clis_v14260.py`` runs ``--check``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from iron_jarvis.providers import subscription_clis as SUBS  # noqa: E402

TS = ROOT / "dashboard" / "lib" / "subscriptionClis.ts"

HEADER = '''/**
 * GENERATED by scripts/gen_subscription_clis.py from
 * src/iron_jarvis/providers/subscription_clis.py — DO NOT EDIT BY HAND
 * (v1.426.0, Wave 6 lane B, E5). Change the Python table, then run
 * `uv run python scripts/gen_subscription_clis.py`; the test
 * tests/test_subscription_clis_v14260.py fails while this file is stale.
 *
 * The CLIs a person SIGNS IN to (a plan, not a key) — every fact the app
 * keeps about each, in one place on both sides.
 */
'''


def render() -> str:
    rows = SUBS.twin_rows()
    body = json.dumps(rows, indent=2, ensure_ascii=False)
    return (
        HEADER
        + "\nexport interface SubscriptionCliRow {\n"
        "  /** Iron Jarvis's provider id. */\n  provider: string;\n"
        "  /** The CLI's own word for itself (Build's account list groups by it). */\n  vendor: string;\n"
        "  /** Iron-Proxy's provider whose accounts it runs as. */\n  proxy: string;\n"
        "  /** The environment variable naming its home. */\n  homeVar: string;\n"
        "  /** Its own default home under the user's profile. */\n  homeDir: string;\n"
        "  /** Build › Code's harness id. */\n  harness: string;\n"
        "  /** The program it runs as. */\n  binary: string;\n"
        "  /** Does Iron Jarvis probe its sign-in (Grok's session file is read instead)? */\n  probed: boolean;\n"
        "  /** The name a person knows the provider by. */\n  name: string;\n"
        "  /** The label on an Iron-Proxy account of it. */\n  accountLabel: string;\n"
        "  /** The model team's short label. */\n  teamLabel: string;\n"
        "}\n\n"
        f"export const SUBSCRIPTION_CLI_ROWS: readonly SubscriptionCliRow[] = {body};\n\n"
        "/** Iron-Proxy provider -> Iron Jarvis provider id. */\n"
        "export const PROXY_TO_PROVIDER: Readonly<Record<string, string>> = Object.fromEntries(\n"
        "  SUBSCRIPTION_CLI_ROWS.map((c) => [c.proxy, c.provider]),\n"
        ");\n\n"
        "/** Iron Jarvis provider id -> the name a person knows it by. */\n"
        "export const SUBSCRIPTION_CLI_NAMES: Readonly<Record<string, string>> = Object.fromEntries(\n"
        "  SUBSCRIPTION_CLI_ROWS.map((c) => [c.provider, c.name]),\n"
        ");\n\n"
        "/** The row for a provider id (undefined: not a subscription CLI). */\n"
        "export function subscriptionCliRow(provider: string): SubscriptionCliRow | undefined {\n"
        "  return SUBSCRIPTION_CLI_ROWS.find((c) => c.provider === provider);\n"
        "}\n"
    )


def main(argv: list[str]) -> int:
    want = render()
    have = TS.read_bytes().decode("utf-8") if TS.exists() else ""
    if "--check" in argv:
        if have.replace("\r\n", "\n") != want:
            print(f"{TS.relative_to(ROOT)} is stale: run `uv run python scripts/gen_subscription_clis.py`")
            return 1
        return 0
    TS.write_bytes(want.encode("utf-8"))
    print(f"wrote {TS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
