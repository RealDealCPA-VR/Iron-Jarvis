"""Generate every built-in tool's words for the dashboard and the desktop
(readiness 12A, G22/G24).

THE GAP: the run log worded every registered built-in (v1.359.0, pinned by
building the real registry), but the approval card and the desktop's ask toast
knew ~50 of them by hand and the chat's work line ~40, so the rest read by
their ids — "The assistant wants to run assign_work", "use pack restart",
"Ran guide_search" counted "ran 1 tool".

ONE SOURCE: ``src/iron_jarvis/agents/mission.py`` — ``card_words`` (the card's
own table ``ASK_WORDS``, the browser tools' words, the run log's lines in the
present) and ``step_line_words`` (the run log's line, done and running). This
script writes, for EVERY tool the real registry registers as a built-in (no
``mcp__`` app tool, no ``custom:`` tool) plus every phrase ``ASK_WORDS`` holds:

* ``dashboard/lib/builtinToolWords.ts`` — the whole file, generated: the card's
  words (read by ``lib/toolWords.toolWords``) and the work line's words for a
  built-in the line does not word by kind (read by ``lib/stepWords``);
* ``desktop/main.js`` — only the text between the ``tool-words:start`` and
  ``tool-words:end`` markers: the toast's copy of the card's words
  (``TOOL_WORDS_BUILTIN``, read by ``askToolWords``). main.js runs in
  Electron's main process and cannot import the dashboard's TypeScript.

``tests/test_tool_words_everywhere_v1387.py`` builds the real registry, fails
on a built-in this source cannot word, and fails when either file is stale.

Usage (from the repo root):
    uv run python scripts/gen_tool_words.py           # write both
    uv run python scripts/gen_tool_words.py --check   # exit 1 when stale
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TS_FILE = ROOT / "dashboard" / "lib" / "builtinToolWords.ts"
JS_FILE = ROOT / "desktop" / "main.js"
JS_START = "// tool-words:start"
JS_END = "// tool-words:end"


def registered_builtins() -> list[str]:
    """Every built-in the REAL registry holds (a throwaway home, offline)."""
    os.environ.setdefault("IRON_PROXY_DATA_DIR", tempfile.mkdtemp(prefix="ij-gen-tool-words-proxy-"))
    from iron_jarvis.platform import build_platform

    platform = build_platform(tempfile.mkdtemp(prefix="ij-gen-tool-words-"))
    return sorted(n for n in platform.registry._tools if not n.startswith(("mcp__", "custom:")))  # noqa: SLF001


def tables(builtins: list[str]) -> tuple[dict[str, str], dict[str, tuple[str, str]]]:
    """``(card words, step words)`` from the one source, sorted by tool."""
    from iron_jarvis.agents import mission

    names = sorted(set(builtins) | set(mission.ASK_WORDS))
    card = {n: mission.card_words(n) for n in names}
    step: dict[str, tuple[str, str]] = {}
    for n in sorted(builtins):
        words = mission.step_line_words(n)
        if words is not None:
            step[n] = words
    return card, step


def render_ts(card: dict[str, str], step: dict[str, tuple[str, str]]) -> str:
    lines = [
        "/**",
        " * GENERATED by scripts/gen_tool_words.py — do not edit by hand. Regenerate:",
        " *   uv run python scripts/gen_tool_words.py",
        " *",
        " * Readiness 12A (G22/G24): what EVERY registered built-in tool does, in the",
        " * words of ONE source (src/iron_jarvis/agents/mission.py: card_words and",
        " * step_line_words), so the approval card (lib/toolWords), the chat's work",
        " * line (lib/stepWords), the desktop's ask toast (desktop/main.js, its own",
        " * generated copy) and the run log say the same thing. Built-ins only, by",
        " * exact name: an app's or a custom tool's words are never written here.",
        " * tests/test_tool_words_everywhere_v1387.py fails when this file is stale.",
        " */",
        "",
        "/** \"The assistant wants to …\": the card's words for each built-in. */",
        "export const BUILTIN_CARD_WORDS: Readonly<Record<string, string>> = {",
    ]
    lines += [f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}," for k, v in card.items()]
    lines += [
        "};",
        "",
        "/** The work line's words for a built-in it does not word by kind:",
        " *  [done, running] — \"Searched your chats\" / \"Searching your chats\". */",
        "export const BUILTIN_STEP_WORDS: Readonly<Record<string, readonly [string, string]>> = {",
    ]
    lines += [
        f"  {json.dumps(k)}: [{json.dumps(d, ensure_ascii=False)}, {json.dumps(g, ensure_ascii=False)}],"
        for k, (d, g) in step.items()
    ]
    lines += ["};", ""]
    return "\n".join(lines)


def render_js_block(card: dict[str, str]) -> str:
    lines = [
        f"{JS_START} (GENERATED by scripts/gen_tool_words.py from agents/mission.py",
        "//: card_words — do not edit by hand; tests/test_tool_words_everywhere_v1387.py",
        "//: fails when it is stale). Readiness 12A (G24): the card's words for EVERY",
        "//: registered built-in, so no toast says \"use pack restart\".",
        "const TOOL_WORDS_BUILTIN = {",
    ]
    lines += [f"  {k}: {json.dumps(v, ensure_ascii=False)}," for k, v in card.items()]
    lines += ["};", JS_END]
    return "\n".join(lines)


def with_js_block(src: str, block: str) -> str:
    start = src.index(JS_START)
    end = src.index(JS_END, start) + len(JS_END)
    return src[:start] + block + src[end:]


def main(argv: list[str]) -> int:
    check = "--check" in argv
    card, step = tables(registered_builtins())
    ts = render_ts(card, step)
    js_src = JS_FILE.read_text(encoding="utf-8")
    js = with_js_block(js_src, render_js_block(card))
    stale = []
    current_ts = TS_FILE.read_text(encoding="utf-8") if TS_FILE.exists() else None
    if current_ts != ts:
        stale.append(str(TS_FILE.relative_to(ROOT)))
    if js != js_src:
        stale.append(str(JS_FILE.relative_to(ROOT)))
    if check:
        if stale:
            print("stale (run: uv run python scripts/gen_tool_words.py): " + ", ".join(stale))
            return 1
        print(f"current: {len(card)} card phrases, {len(step)} work-line phrases")
        return 0
    TS_FILE.write_text(ts, encoding="utf-8", newline="\n")
    JS_FILE.write_text(js, encoding="utf-8", newline="\n")
    print(f"wrote {len(card)} card phrases, {len(step)} work-line phrases")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
