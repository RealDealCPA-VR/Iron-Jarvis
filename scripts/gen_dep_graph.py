_TEST_IMPORTS: dict[str, set[str]] = {}


def _test_imports() -> dict[str, set[str]]:
    """test file -> every iron_jarvis module name it imports (parsed, cached).
    A string naming a module (monkeypatch.setattr("iron_jarvis.x.y.f", ...))
    counts too: the test pins that module."""
    if _TEST_IMPORTS:
        return _TEST_IMPORTS
    named = re.compile(r"""["'](iron_jarvis(?:\.\w+)+)""")
    for path in sorted(TESTS.rglob("test_*.py")):
        text = path.read_text(encoding="utf-8", errors="replace")
        try:
            tree = _parse(text)
        except SyntaxError:
            continue
        found = {t for t in _imports_in(tree, "tests.x", False) if t.startswith(PKG)}
        found |= set(named.findall(text))
        _TEST_IMPORTS[path.relative_to(ROOT).as_posix()] = found
    return _TEST_IMPORTS


def _tests_importing(modules: set[str]) -> list[str]:
    """Test files that import any of these modules (or name one in a string)."""
    if not modules:
        return []
    return [f for f, names in _test_imports().items()
            if any(n in modules or any(n.startswith(m + ".") for m in modules) for n in names)]


def _undo_msys(t: str) -> str:
    """Git Bash rewrites an argument that starts with '/' into a Windows path
    ('/clients' -> 'C:/Program Files/Git/clients'). Undo that."""
    at = t.startswith("@")
    body = t[1:] if at else t
    m = re.match(r"^[A-Za-z]:/.*?/Git(?:/usr)?(/.*)$", body)
    if m and not Path(body).exists():
        body = m.group(1)
    return ("@" + body) if at else body


def _vitest_importing(files: set[str]) -> list[str]:
    if not files:
        return []
    stems = {"@/" + f.removeprefix("dashboard/").rsplit(".", 1)[0] for f in files}
    hits = []
    for path in sorted((DASH / "__tests__").rglob("*.test.ts*")):
        text = path.read_text(encoding="utf-8", errors="replace")
        if any(f'"{s}"' in text or f"'{s}'" in text for s in stems):
            hits.append(path.relative_to(ROOT).as_posix())
    return hits


def _closure(start: set[str], rev: dict[str, set[str]]) -> set[str]:
    seen = set(start)
    todo = list(start)
    while todo:
        for nxt in rev.get(todo.pop(), ()):
            if nxt not in seen:
                seen.add(nxt)
                todo.append(nxt)
    return seen - start


def impact(g: Graph, target: str) -> str:
    out: list[str] = []
    rev = g.reverse_modules()
    t = _undo_msys(target.strip().replace("\\", "/"))

    # A daemon route?
    if t.startswith("/"):
        pre = "/" + t.strip("/").split("/")[0]
        served = sorted(g.routes.get(pre, ()))
        dash = sorted(f for f, c in g.dash_calls.items() if pre in c)
        out.append(f"Route {pre}")
        out.append(f"  served by: {', '.join(served) or 'no daemon file'}")
        out.append(f"  called from {len(dash)} dashboard file(s):")
        out += [f"    {f}" for f in dash]
        out.append("  tests to run:")
        mods = {m for m, p in g.route_mods.items() if pre in p}
        calls = re.compile(r"""["'`]""" + re.escape(pre) + r"""(?=[/?"'`])""")
        py = set(_tests_importing(mods))
        for path in sorted(TESTS.rglob("test_*.py")):
            if calls.search(path.read_text(encoding="utf-8", errors="replace")):
                py.add(path.relative_to(ROOT).as_posix())
        out += [f"    {x}" for x in sorted(py)]
        out += [f"    {x}" for x in _vitest_importing(set(dash))]
        return "\n".join(out)

    # A Python library?
    deps = _py_deps()
    if t.lower() in deps:
        names = set(_import_names(t.lower())) or ({"winrt"} if t.lower().startswith("winrt") else set())
        users = sorted(m for m, ext in g.mod_external.items() if ext & names)
        out.append(f"Python library {t} ({deps[t.lower()]}), imported as {', '.join(sorted(names))}")
        out.append(f"  imported directly in {len(users)} file(s):")
        out += [f"    {g.modules[m].relative_to(ROOT).as_posix()}" for m in users]
        ring = _closure(set(users), rev)
        out.append(f"  reached through them by {len(ring)} more file(s) in "
                   f"{len({_package_of(m) for m in ring})} package(s)")
        out.append("  tests to run (they import a file that imports it):")
        out += [f"    {x}" for x in _tests_importing(set(users))]
        out.append("  also: check the frozen build if the wheel is native (packaging/ironjarvis.spec)")
        return "\n".join(out)

    # An npm package?
    npm = _npm_deps()
    if t in npm:
        users = sorted(f for f, p in g.dash_npm.items() if t in p)
        out.append(f"npm package {t} ({npm[t]})")
        out.append(f"  imported in {len(users)} dashboard file(s):")
        out += [f"    {f}" for f in users]
        out.append("  vitest files to run:")
        out += [f"    {x}" for x in _vitest_importing(set(users))]
        out.append("  then: cd dashboard && npx tsc --noEmit && pnpm build")
        return "\n".join(out)

    # A dashboard file?
    if t.startswith("dashboard/") or t.startswith("@/"):
        rel = "dashboard/" + t[2:] if t.startswith("@/") else t
        matches = [f for f in g.dash_imports if f == rel or f.rsplit(".", 1)[0] == rel]
        if not matches:
            return f"No dashboard file {t} under {', '.join(DASH_FOLDERS)}."
        f = matches[0]
        rdash = g.reverse_dash()
        direct = sorted(rdash.get(f, ()))
        ring = _closure({f}, rdash)
        out.append(f"Dashboard file {f}")
        out.append(f"  calls daemon routes: {', '.join(sorted(g.dash_calls[f])) or 'none'}")
        out.append(f"  imported directly by {len(direct)} file(s):")
        out += [f"    {x}" for x in direct]
        out.append(f"  reached by {len(ring)} file(s) in all")
        out.append("  vitest files to run:")
        out += [f"    {x}" for x in _vitest_importing({f} | set(direct))]
        return "\n".join(out)

    # A Python file or package.
    if t.endswith(".py"):
        p = (ROOT / t).resolve() if not Path(t).is_absolute() else Path(t)
        mods = {m for m, path in g.modules.items() if path.resolve() == p}
    else:
        dotted = t.replace("/", ".").removeprefix("src.").removesuffix(".")
        if not dotted.startswith(PKG):
            dotted = f"{PKG}.{dotted}"
        mods = {m for m in g.modules if m == dotted or m.startswith(dotted + ".")}
    if not mods:
        return (f"Nothing called {t!r}: not a file or package under src/iron_jarvis/, "
                "a pyproject library, an npm dependency, a dashboard file or a /route.")
    direct = set().union(*(rev.get(m, set()) for m in mods)) - mods
    ring = _closure(mods, rev) - direct
    label = t if len(mods) == 1 else f"{t} ({len(mods)} files)"
    out.append(f"Python {label}")
    out.append(f"  imported directly by {len(direct)} file(s) outside it:")
    by_pkg: dict[str, list[str]] = defaultdict(list)
    for m in sorted(direct):
        by_pkg[_package_of(m)].append(g.modules[m].relative_to(ROOT).as_posix())
    for pkg in sorted(by_pkg):
        out.append(f"    [{pkg}, {g.area_of(pkg)}]")
        out += [f"      {x}" for x in by_pkg[pkg]]
    pk = sorted({_package_of(m) for m in ring})
    out.append(f"  reached through those by {len(ring)} more file(s) in {len(pk)} package(s): {', '.join(pk)}")
    routes = sorted(set().union(*(g.route_mods.get(m, set()) for m in mods | direct)))
    if routes:
        out.append(f"  daemon routes served here or by a direct importer: {', '.join(routes)}")
        folders = sorted({_dash_folder(f) for f, c in g.dash_calls.items() if c & set(routes)})
        out.append(f"  dashboard folders calling those routes: {', '.join(folders) or 'none'}")
    tests = _tests_importing(mods)
    near = [x for x in _tests_importing(direct) if x not in tests]
    out.append(f"  tests that import it ({len(tests)}):")
    out += [f"    {x}" for x in tests]
    out.append(f"  tests that import a direct importer ({len(near)}; run these too if the change alters behaviour):")
    out += [f"    {x}" for x in near[:60]]
    if len(near) > 60:
        out.append(f"    ... and {len(near) - 60} more")
    return "\n".join(out)


