def self_area(g: "Graph", pkg: str) -> str:
    """The rules area of a package, as the CLAUDE.md table names it."""
    return g.areas.get(pkg, "?")


def _names(items: set[str] | list[str]) -> str:
    items = sorted(items)
    if not items:
        return "none"
    return ", ".join(items)


def _sccs(nodes: list[str], edges: dict[str, set[str]]) -> list[list[str]]:
    """Tarjan's strongly connected components, iteratively; only those with 2+ members."""
    index: dict[str, int] = {}
    low: dict[str, int] = {}
    on: set[str] = set()
    stack: list[str] = []
    out: list[list[str]] = []
    counter = 0
    for start in nodes:
        if start in index:
            continue
        work = [(start, iter(sorted(edges.get(start, ()))))]
        index[start] = low[start] = counter
        counter += 1
        stack.append(start)
        on.add(start)
        while work:
            node, it = work[-1]
            advanced = False
            for nxt in it:
                if nxt not in index:
                    index[nxt] = low[nxt] = counter
                    counter += 1
                    stack.append(nxt)
                    on.add(nxt)
                    work.append((nxt, iter(sorted(edges.get(nxt, ())))))
                    advanced = True
                    break
                if nxt in on:
                    low[node] = min(low[node], index[nxt])
            if advanced:
                continue
            work.pop()
            if work:
                low[work[-1][0]] = min(low[work[-1][0]], low[node])
            if low[node] == index[node]:
                comp = []
                while True:
                    w = stack.pop()
                    on.discard(w)
                    comp.append(w)
                    if w == node:
                        break
                if len(comp) > 1:
                    out.append(sorted(comp))
    return sorted(out, key=lambda c: (-len(c), c))


def render(g: Graph) -> str:
    edges = g.pkg_edges()             # every import: what can break at run time
    eager = g.pkg_edges(eager=True)   # load-time imports: the layering
    pkgs = g.packages()
    rev: dict[str, set[str]] = defaultdict(set)
    for a, bs in edges.items():
        for b in bs:
            rev[b].add(a)
    lines: list[str] = [HEADER]

    # -- Areas (load-time imports only) -------------------------------------
    area_edges: dict[str, set[str]] = defaultdict(set)
    for a, bs in eager.items():
        if a in GLUE:
            continue  # the composition roots import everything
        for b in bs:
            if b in GLUE:
                continue
            aa, bb = g.area_of(a), g.area_of(b)
            if aa != bb:
                area_edges[aa].add(bb)
    areas = sorted({g.area_of(p) for p in pkgs if p not in GLUE})
    lines += [
        "## Areas",
        "",
        "Each box is an area from the `CLAUDE.md` table (its rules are in",
        "`docs/rules/<area>.md`). The picture uses **load-time** imports only (the",
        "`import` lines at the top of a file), which show how the code is layered.",
        "Arrows into `core` are left out because every area has one. `core` here",
        "is `core/` plus `maintenance.py` and the package root. The two",
        "composition roots, `platform.py` (builds every subsystem once) and",
        "`daemon/` (the app factory and the routes), import every area and are",
        "left out. Imports inside functions add many more edges: see the",
        "package table for the full blast radius.",
        "",
        "```mermaid",
        "flowchart TD",
    ]
    for a in areas:
        lines.append(f'  {a.replace("?", "unclaimed")}["{a}"]')
    for a in areas:
        for b in sorted(area_edges.get(a, ())):
            if b != "core":
                lines.append(f"  {a} --> {b}")
    lines += ["```", "", "| Area | Imports at load time | Imported at load time by |", "|---|---|---|"]
    by_area = {a: sorted(x for x in areas if a in area_edges.get(x, ())) for a in areas}
    for a in sorted(areas, key=lambda x: (-len(by_area[x]), x)):
        lines.append(f"| {a} | {_names(area_edges.get(a, set()))} | {_names(by_area[a])} |")
    lines.append("")

    # -- Packages ----------------------------------------------------------
    lines += [
        "## Packages",
        "",
        "One row per package under `src/iron_jarvis/`, most-depended-on first.",
        "\"Imported by\" counts every import, including those inside functions:",
        "it is the blast radius, every package a change here can break. \"Imports\"",
        "splits what the package needs to load from what it reaches only when a",
        "function runs.",
        "",
        "| Package | Area | Files | Imported by | Imports at load time | Imports inside functions only |",
        "|---|---|---:|---|---|---|",
    ]
    files_in: dict[str, int] = defaultdict(int)
    for m in g.modules:
        files_in[_package_of(m)] += 1
    for p in sorted(pkgs, key=lambda x: (-len(rev.get(x, ())), x)):
        by = rev.get(p, set())
        by_txt = f"**{len(by)}**: {_names(by)}" if by else "none"
        load = eager.get(p, set())
        lazy = edges.get(p, set()) - load
        lines.append(f"| `{p}` | {self_area(g, p)} | {files_in[p]} | {by_txt} | {_names(load)} | {_names(lazy)} |")
    lines.append("")

    cycles = _sccs(pkgs, eager)
    whole = _sccs(pkgs, edges)
    biggest = len(whole[0]) if whole else 0
    lines += [
        "## Packages that import each other at load time",
        "",
        "Packages in one group import each other in their top-level `import`",
        "lines, so the order they load in matters. Treat a group as one unit when",
        "you upgrade, and never add a load-time import that makes a group bigger:",
        "import inside the function instead.",
        "",
    ]
    if cycles:
        for i, comp in enumerate(cycles, 1):
            lines.append(f"{i}. ({len(comp)}) {', '.join(f'`{c}`' for c in comp)}")
    else:
        lines.append("None.")
    lines += [
        "",
        f"Counting imports inside functions too, {biggest} of the {len(pkgs)} packages",
        "reach one another, so at run time almost any change can reach almost",
        "anything. That is why `--impact` lists the direct importers by file and",
        "the tests that import them.",
        "",
    ]

    # -- Python libraries --------------------------------------------------
    import_to_pkgs: dict[str, set[str]] = defaultdict(set)
    for mod, ext in g.mod_external.items():
        for name in ext:
            import_to_pkgs[name].add(_package_of(mod))
    lines += [
        "## Python libraries",
        "",
        "From `pyproject.toml` (the `dev` extra left out). Before upgrading a library,",
        "run `--impact <name>` for the files and the tests. A native wheel also needs",
        "its `packaging/ironjarvis.spec` entry checked on the frozen build.",
        "",
        "| Library | Requirement | Imported in |",
        "|---|---|---|",
    ]
    for dist, req in sorted(_py_deps().items()):
        if dist.startswith("winrt-") and dist != "winrt-runtime":
            continue
        users: set[str] = set()
        for name in _import_names(dist):
            users |= import_to_pkgs.get(name, set())
        if dist == "winrt-runtime":
            req = "`winrt-*` (7 wheels, Windows only)"
        else:
            req = f"`{req}`"
        if dist in INDIRECT and not users:
            where = "not imported directly (pulled in by another library)"
        else:
            where = _names(users) if users else "not imported directly"
        lines.append(f"| {dist} | {req} | {where} |")
    lines.append("")

    # -- Routes ------------------------------------------------------------
    callers: dict[str, set[str]] = defaultdict(set)
    for f, prefixes in g.dash_calls.items():
        for pre in prefixes:
            callers[pre].add(_dash_folder(f))
    lines += [
        "## Daemon routes and the dashboard",
        "",
        "Grouped by the first part of the path. \"Dashboard folders\" are the folders",
        "whose code names that path in a string (a text scan). It over-reports a",
        "page link that shares a route's name, such as `/settings`, and misses a",
        "path assembled from pieces, so search before you delete a route.",
        "",
        "| Route | Served by | Dashboard folders |",
        "|---|---|---|",
    ]
    for pre in sorted(set(g.routes) | {p for p in callers if p in g.routes}):
        served = ", ".join(f"`{s.removeprefix('src/iron_jarvis/')}`" for s in sorted(g.routes[pre]))
        lines.append(f"| `{pre}` | {served} | {_names(callers.get(pre, set()))} |")
    lines.append("")

    # -- npm ---------------------------------------------------------------
    npm_users: dict[str, set[str]] = defaultdict(set)
    for f, pkgs_used in g.dash_npm.items():
        for n in pkgs_used:
            npm_users[n].add(_dash_folder(f))
    lines += [
        "## Dashboard packages (npm)",
        "",
        "From `dashboard/package.json` `dependencies`. After an upgrade run",
        "`pnpm build` (it must reach \"Generating static pages\") and the vitest",
        "files `--impact` names.",
        "",
        "| Package | Version | Used in |",
        "|---|---|---|",
    ]
    for name, ver in _npm_deps().items():
        used = npm_users.get(name, set())
        lines.append(f"| {name} | `{ver}` | {_names(used) if used else 'not imported in app/components/lib'} |")
    lines.append("")
    return "\n".join(lines)


