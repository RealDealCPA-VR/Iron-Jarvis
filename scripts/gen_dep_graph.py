def _load_areas() -> dict[str, str]:
    """package name -> area, from gen_agent_rules.PACKAGE_AREAS."""
    path = ROOT / "scripts" / "gen_agent_rules.py"
    spec = importlib.util.spec_from_file_location("_gen_agent_rules_for_deps", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    out: dict[str, str] = {}
    for area, names in module.PACKAGE_AREAS.items():
        for name in names:
            out[name.removesuffix(".py")] = area
    return out


def _module_name(path: Path) -> str:
    rel = path.relative_to(SRC.parent).with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def _package_of(module: str) -> str | None:
    """'iron_jarvis.workmap.clients.store' -> 'workmap'."""
    parts = module.split(".")
    if parts[0] != PKG:
        return None
    return parts[1] if len(parts) > 1 else "__init__"


def _parse(source: str) -> ast.Module:
    """ast.parse without the SyntaxWarnings old files raise (bad escapes)."""
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", SyntaxWarning)
        return ast.parse(source)


def _eager_part(tree: ast.Module) -> ast.Module:
    """The imports that run when the module loads: top level, including inside a
    top-level ``try``/``if``, but not under ``if TYPE_CHECKING`` (type-only)."""
    found: list[ast.stmt] = []

    def walk(stmts: list[ast.stmt]) -> None:
        for st in stmts:
            if isinstance(st, (ast.Import, ast.ImportFrom)):
                found.append(st)
            elif isinstance(st, ast.If):
                if "TYPE_CHECKING" in ast.unparse(st.test):
                    continue
                walk(st.body)
                walk(st.orelse)
            elif isinstance(st, ast.Try):
                walk(st.body)
                walk(st.orelse)
                walk(st.finalbody)
                for handler in st.handlers:
                    walk(handler.body)

    walk(tree.body)
    return ast.Module(body=found, type_ignores=[])


def _imports_in(tree: ast.AST, module: str, is_pkg: bool) -> set[str]:
    """Every module name this file imports (absolute, dotted)."""
    found: set[str] = set()
    base = module.split(".") if is_pkg else module.split(".")[:-1]
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                found.add(alias.name)
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                anchor = base[: len(base) - (node.level - 1)] if node.level > 1 else base
                prefix = ".".join(anchor)
                target = f"{prefix}.{node.module}" if node.module else prefix
            else:
                target = node.module or ""
            if not target:
                continue
            found.add(target)
            # `from pkg import sub` may name a submodule; keep the candidates.
            for alias in node.names:
                if alias.name != "*":
                    found.add(f"{target}.{alias.name}")
    return found


class Graph:
    """Everything the page and the impact query need, read once."""

    def __init__(self) -> None:
        self.areas = _load_areas()
        self.modules: dict[str, Path] = {}
        self.mod_imports: dict[str, set[str]] = {}        # module -> internal modules (all)
        self.mod_eager: dict[str, set[str]] = {}          # module -> internal modules at load time
        self.mod_external: dict[str, set[str]] = {}       # module -> top-level external names
        self.routes: dict[str, set[str]] = defaultdict(set)  # "/clients" -> daemon files
        self.route_mods: dict[str, set[str]] = defaultdict(set)  # module -> route prefixes
        self._read_python()
        self.dash_imports: dict[str, set[str]] = {}       # dashboard file -> dashboard files
        self.dash_npm: dict[str, set[str]] = {}           # dashboard file -> npm packages
        self.dash_calls: dict[str, set[str]] = {}         # dashboard file -> route prefixes
        self._read_dashboard()

    # -- Python ------------------------------------------------------------
    def _read_python(self) -> None:
        trees: dict[str, tuple[ast.AST, bool]] = {}
        for path in sorted(SRC.rglob("*.py")):
            if "__pycache__" in path.parts:
                continue
            name = _module_name(path)
            self.modules[name] = path
            source = path.read_text(encoding="utf-8", errors="replace")
            try:
                tree = _parse(source)
            except SyntaxError:
                tree = ast.Module(body=[], type_ignores=[])
            trees[name] = (tree, path.name == "__init__.py")
        known = set(self.modules)

        def resolve(targets: set[str], name: str) -> set[str]:
            internal: set[str] = set()
            for target in targets:
                if target.split(".")[0] != PKG:
                    continue
                # Resolve to the longest known module ('a.b.func' -> 'a.b').
                parts = target.split(".")
                while parts and ".".join(parts) not in known:
                    parts.pop()
                if parts and ".".join(parts) != name:
                    internal.add(".".join(parts))
            return internal

        for name, (tree, is_pkg) in trees.items():
            targets = _imports_in(tree, name, is_pkg)
            self.mod_imports[name] = resolve(targets, name)
            self.mod_eager[name] = resolve(_imports_in(_eager_part(tree), name, is_pkg), name)
            self.mod_external[name] = {
                t.split(".")[0] for t in targets
                if t.split(".")[0] not in (PKG, "", "__future__")
                and t.split(".")[0] not in sys.stdlib_module_names}
            if name.startswith(f"{PKG}.daemon"):
                rel = self.modules[name].relative_to(ROOT).as_posix()
                for prefix in _route_prefixes(tree):
                    self.routes[prefix].add(rel)
                    self.route_mods[name].add(prefix)

    # -- Dashboard ---------------------------------------------------------
    def _dash_files(self) -> list[Path]:
        files: list[Path] = []
        for folder in DASH_FOLDERS:
            base = DASH / folder
            if not base.is_dir():
                continue
            for path in sorted(base.rglob("*")):
                if path.suffix in (".ts", ".tsx") and not any(p in DASH_SKIP for p in path.parts):
                    files.append(path)
        return files

    def _read_dashboard(self) -> None:
        npm = set(_npm_deps())
        files = self._dash_files()
        rels = {p.relative_to(ROOT).as_posix() for p in files}
        for path in files:
            rel = path.relative_to(ROOT).as_posix()
            text = path.read_text(encoding="utf-8", errors="replace")
            local: set[str] = set()
            pkgs: set[str] = set()
            for spec in _TS_IMPORT.findall(text):
                spec = spec[0] or spec[1]
                if spec.startswith("@/") or spec.startswith("."):
                    hit = _resolve_ts(path, spec, rels)
                    if hit:
                        local.add(hit)
                else:
                    name = "/".join(spec.split("/")[:2]) if spec.startswith("@") else spec.split("/")[0]
                    if name in npm:
                        pkgs.add(name)
            self.dash_imports[rel] = local
            self.dash_npm[rel] = pkgs
            self.dash_calls[rel] = {"/" + m for m in _TS_PATH.findall(text)} & set(self.routes)

    # -- Derived views -----------------------------------------------------
    def pkg_edges(self, eager: bool = False) -> dict[str, set[str]]:
        edges: dict[str, set[str]] = defaultdict(set)
        for mod, targets in (self.mod_eager if eager else self.mod_imports).items():
            src = _package_of(mod)
            for t in targets:
                dst = _package_of(t)
                if src and dst and dst != src:
                    edges[src].add(dst)
        return edges

    def packages(self) -> list[str]:
        return sorted({_package_of(m) for m in self.modules if _package_of(m)})

    def area_of(self, pkg: str) -> str:
        if pkg in BASE:
            return "core"  # the shared base, drawn apart from the daemon glue
        return self.areas.get(pkg, "?")

    def reverse_modules(self) -> dict[str, set[str]]:
        rev: dict[str, set[str]] = defaultdict(set)
        for mod, targets in self.mod_imports.items():
            for t in targets:
                rev[t].add(mod)
        return rev

    def reverse_dash(self) -> dict[str, set[str]]:
        rev: dict[str, set[str]] = defaultdict(set)
        for f, targets in self.dash_imports.items():
            for t in targets:
                rev[t].add(f)
        return rev


_TS_IMPORT = re.compile(
    r"""(?:import|export)\s[^;'"`]*?from\s*["']([^"']+)["']|(?:import|require)\(\s*["']([^"']+)["']\s*\)""")
#: A string literal (or `${API_BASE}/...`) that starts with a path: "/clients/...".
#: Kept only when the daemon serves that first part, so it over-reports a page
#: link that shares a route's name (/settings, /skills) rather than miss a caller.
_TS_PATH = re.compile(r"""(?:[`'"]|\$\{API_BASE\})/([A-Za-z0-9_-]+)(?=[/?`'"#$])""")


def _resolve_ts(path: Path, spec: str, rels: set[str]) -> str | None:
    if spec.startswith("@/"):
        base = (DASH / spec[2:]).as_posix()
    else:
        base = (path.parent / spec).resolve().as_posix()
    root = ROOT.as_posix()
    if not base.startswith(root):
        return None
    base = base[len(root) + 1:]
    for cand in (base, base + ".ts", base + ".tsx", base + "/index.ts", base + "/index.tsx"):
        if cand in rels:
            return cand
    return None


def _route_prefixes(tree: ast.AST) -> set[str]:
    found: set[str] = set()
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for dec in node.decorator_list:
            if (isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute)
                    and dec.func.attr in HTTP_METHODS and dec.args
                    and isinstance(dec.args[0], ast.Constant) and isinstance(dec.args[0].value, str)):
                route = dec.args[0].value
                seg = route.strip("/").split("/")[0]
                found.add("/" + seg if seg and not seg.startswith("{") else "/")
    return found


def _py_deps() -> dict[str, str]:
    """distribution -> requirement line, from pyproject (base + extras)."""
    data = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    proj = data.get("project", {})
    lines = list(proj.get("dependencies", []))
    for extra, reqs in sorted(proj.get("optional-dependencies", {}).items()):
        if extra != "dev":
            lines += reqs
    out: dict[str, str] = {}
    for line in lines:
        name = re.split(r"[\[<>=!~;\s]", line, maxsplit=1)[0].lower()
        out[name] = line.split(";")[0].strip()
    return out


def _npm_deps() -> dict[str, str]:
    data = json.loads((DASH / "package.json").read_text(encoding="utf-8"))
    return dict(sorted(data.get("dependencies", {}).items()))


def _import_names(dist: str) -> tuple[str, ...]:
    if dist in DIST_IMPORTS:
        return DIST_IMPORTS[dist]
    if dist.startswith("winrt-"):
        return ()  # all winrt-* wheels are imported as `winrt`, counted under winrt-runtime
    return (dist.replace("-", "_"),)


def _dash_folder(rel: str) -> str:
    """'dashboard/components/chat/X.tsx' -> 'components/chat'; 'dashboard/lib/x.ts' -> 'lib'."""
    parts = rel.split("/")[1:-1]
    if not parts:
        return "."
    if parts[0] == "lib":
        return "lib"
    return "/".join(parts[:2])


