def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/DEPENDENCIES.md is out of step")
    ap.add_argument("--impact", metavar="TARGET", help="a package, .py file, dashboard file, library or /route")
    args = ap.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8")
    g = Graph()
    if args.impact:
        print(impact(g, args.impact))
        return 0
    text = render(g)
    if args.check:
        current = OUT.read_bytes().decode("utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("docs/DEPENDENCIES.md is out of step with the code. Run:\n"
                  "  uv run python scripts/gen_dep_graph.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT).as_posix()} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
