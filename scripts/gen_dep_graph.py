"""The dependency graph: what imports what, read from the code itself.

Before an upgrade (a library, a package, a route) you want to know what else
moves with it. This script reads the source and answers that two ways:

    uv run python scripts/gen_dep_graph.py              # write docs/DEPENDENCIES.md
    uv run python scripts/gen_dep_graph.py --check      # exit 1 if that file is out of step
    uv run python scripts/gen_dep_graph.py --impact workmap
    uv run python scripts/gen_dep_graph.py --impact src/iron_jarvis/workmap/clients/store.py
    uv run python scripts/gen_dep_graph.py --impact pypdf        # a Python library
    uv run python scripts/gen_dep_graph.py --impact /clients     # a daemon route
    uv run python scripts/gen_dep_graph.py --impact next         # a dashboard npm package

``docs/DEPENDENCIES.md`` holds the coarse, slow-changing picture (areas,
packages, libraries, routes). ``--impact`` answers at file level for one
target: who imports it, which routes and dashboard folders sit on top of it,
and which test files to run locally.

What it reads
-------------
* Python: every ``import`` in ``src/iron_jarvis/`` (top-level AND inside
  functions: a lazy import is still a dependency), parsed with ``ast``.
* Daemon routes: ``@app.get("/x...")`` style decorators under ``daemon/``.
* Dashboard: ``import ... from`` lines and calls such as ``get("/x...")`` in
  ``dashboard/{app,components,lib}`` (a text scan, so a path built at run
  time is not seen).
* Libraries: ``pyproject.toml`` dependencies and ``dashboard/package.json``.

Areas come from ``PACKAGE_AREAS`` in ``scripts/gen_agent_rules.py`` (one table,
not two). Stdlib only. Output is UTF-8 with LF line ends and sorted, so it is
the same on Windows and Linux.
"""

