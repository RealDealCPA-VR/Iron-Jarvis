"""Split the old, single CLAUDE.md into area rule files. Run once per source.

Why this exists
---------------
Until 2026-11-14 every rule for every part of Iron Jarvis lived in one
CLAUDE.md (about 19,500 lines, 1.4 MB), which every agent session loaded in
full before its first word. This script MOVES that text; it never rewrites it:

* the whole old file is kept byte for byte as ``docs/rules/ARCHIVE-<date>.md``;
* every top-level bullet goes, unchanged, into exactly one area file under
  ``docs/rules/``;
* ``docs/rules/SPLIT-RECORD-<date>.md`` lists every piece of the old file, the
  lines it came from, a hash of its text, and where it went.

The sorting is NOT decided here by guesswork at run time. It is read from
``scripts/agent_rules_split_table.tsv`` (one row per bullet, reviewed by hand).
A bullet that is not in the table stops the run and is named, so a bullet added
to the old file by another session can never be dropped or sorted silently.

Usage
-----
    uv run python scripts/split_agent_rules.py propose SOURCE   # print a first sorting
    uv run python scripts/split_agent_rules.py split   SOURCE   # write the files
    uv run python scripts/split_agent_rules.py split   SOURCE --again   # before it lands only
    uv run python scripts/split_agent_rules.py verify           # re-check what was written

``SOURCE`` is the old full file (a copy of CLAUDE.md from before the split).
After ``split`` run ``uv run python scripts/gen_agent_rules.py`` to write each
area file's contents list and the folder pointers.

All output is written with LF line ends and UTF-8, whatever the platform.
"""

