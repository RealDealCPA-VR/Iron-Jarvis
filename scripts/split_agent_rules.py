@dataclass
class Segment:
    kind: str  # "section" (non-bullet text) or "bullet"
    section: str  # the `## ` section it sits in
    start: int  # 1-based first line in the source
    end: int  # 1-based last line (inclusive)
    text: str  # exact text, own trailing blank lines included
    key: str = ""  # stable key for the table (bullets only)
    headline: str = ""
    version: str = ""
    dest: str = ""  # area id, or "root"
    also: list[str] = field(default_factory=list)

    @property
    def body(self) -> str:
        """The text without trailing blank lines (what is hashed and moved)."""
        return self.text.rstrip("\n")

    @property
    def sha(self) -> str:
        return hashlib.sha256(self.body.encode("utf-8")).hexdigest()


def read_lf(path: Path) -> str:
    """Read as UTF-8 with LF line ends (a CRLF checkout must not change a hash)."""
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def write_lf(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.replace("\r\n", "\n").encode("utf-8"))


def _flat(text: str, limit: int = 1500) -> str:
    return re.sub(r"\s+", " ", text[:limit]).strip()


def headline_of(text: str) -> tuple[str, str]:
    """(headline, first version named) of a bullet. Pure; reads the bullet only."""
    flat = _flat(text[2:] if text.startswith("- ") else text)
    m = re.match(r"\*\*(.+?)\*\*", flat)
    head = m.group(1).strip() if m else flat[:110].strip()
    ver = re.search(r"\bv(1\.\d+\.\d+)", flat[:700])
    return head, (ver.group(1) if ver else "")


def key_of(headline: str) -> str:
    return re.sub(r"[^a-z0-9]+", " ", headline.lower()).strip()[:90]


def parse(source: str) -> list[Segment]:
    """Cut the old file into pieces that, joined in order, are the file again."""
    lines = source.split("\n")
    whole = {"(title and introduction)", "The three processes", "Commands",
             "Release flow (how the user receives your work)"}
    segs: list[Segment] = []
    section = "(title and introduction)"
    kind = "section"
    start = 0

    def close(end: int) -> None:
        if end <= start:
            return
        segs.append(Segment(kind, section, start + 1, end, "\n".join(lines[start:end])))

    for i, line in enumerate(lines):
        new_section = line.startswith("## ")
        new_bullet = line.startswith("- ") and section not in whole
        if not (new_section or new_bullet):
            continue
        close(i)
        start = i
        if new_section:
            section = line[3:].strip()
            kind = "section"
        else:
            kind = "bullet"
    close(len(lines))

    # The pieces are joined by the newline that separated their lines.
    if "\n".join(s.text for s in segs) != source:
        raise SystemExit("parse error: the pieces do not join back into the source")

    seen: dict[str, int] = {}
    for s in segs:
        if s.kind != "bullet":
            s.headline = s.section
            continue
        s.headline, s.version = headline_of(s.text)
        base = key_of(s.headline)
        seen[base] = seen.get(base, 0) + 1
        s.key = base if seen[base] == 1 else f"{base} #{seen[base]}"
    return segs


def scores(text: str) -> dict[str, float]:
    out: dict[str, float] = {}
    for area, sigs in SIGNALS.items():
        total = 0.0
        for pattern, weight in sigs:
            n = len(re.findall(pattern, text))
            # A word said forty times is not forty times the evidence.
            total += weight * min(n, 6)
        out[area] = total
    return out


def propose(segs: list[Segment]) -> None:
    rows = []
    for s in segs:
        if s.kind != "bullet":
            continue
        sc = sorted(scores(s.text).items(), key=lambda kv: -kv[1])
        best, second, third = sc[0], sc[1], sc[2]
        total = sum(v for _, v in sc) or 1.0
        also = [a for a, v in sc[1:4] if v / total >= 0.18 and v >= 8]
        rows.append((s, best, second, third, also))
    for n, (s, best, second, third, also) in enumerate(rows, 1):
        print(
            f"{n:3d} L{s.start:<5d} {s.end - s.start + 1:4d}l "
            f"{best[0]}:{best[1]:.0f} {second[0]}:{second[1]:.0f} {third[0]}:{third[1]:.0f} "
            f"| {s.section[:4]} | v{s.version or '-'} | {s.headline[:100]}"
        )
    if not TABLE.exists():
        out = ["# key\tarea\talso (comma separated)\theadline (for the reader; not used)"]
        for s, best, _second, _third, also in rows:
            out.append(f"{s.key}\t{best[0]}\t{','.join(also)}\t{s.headline[:120]}")
        write_lf(TABLE, "\n".join(out) + "\n")
        print(f"\nwrote a first table: {TABLE}", file=sys.stderr)


def load_table() -> dict[str, tuple[str, list[str]]]:
    table: dict[str, tuple[str, list[str]]] = {}
    for n, raw in enumerate(read_lf(TABLE).split("\n"), 1):
        if not raw.strip() or raw.startswith("#"):
            continue
        cols = raw.split("\t")
        if len(cols) < 3:
            raise SystemExit(f"{TABLE.name} line {n}: expected key<TAB>area<TAB>also")
        key, area, also = cols[0], cols[1], [a for a in cols[2].split(",") if a]
        for a in [area, *also]:
            if a not in AREAS:
                raise SystemExit(f"{TABLE.name} line {n}: unknown area {a!r}")
        if key in table:
            raise SystemExit(f"{TABLE.name} line {n}: the key {key!r} is listed twice")
        table[key] = (area, [a for a in also if a != area])
    return table


def assign(segs: list[Segment]) -> None:
    table = load_table()
    missing = []
    used = set()
    for s in segs:
        if s.kind == "bullet":
            row = table.get(s.key)
            if row is None:
                best = max(scores(s.text).items(), key=lambda kv: kv[1])[0]
                missing.append(f"  line {s.start}: {s.headline[:100]}\n    key: {s.key}\n    suggested area: {best}")
                continue
            used.add(s.key)
            s.dest, s.also = row
        else:
            fate = SECTION_FATE.get(s.section)
            if fate is None:
                raise SystemExit(f"a `## {s.section}` section has no entry in SECTION_FATE")
            s.dest = fate
    if missing:
        raise SystemExit(
            "These bullets are not in the sorting table. Add a row for each to "
            f"{TABLE.name} (key<TAB>area<TAB>also) and run again:\n" + "\n".join(missing)
        )
    # A row with no bullet is not an error by itself: the table may already hold
    # a bullet another branch has not landed yet. A bullet whose headline CHANGED
    # is caught above (it is "not in the table"), so nothing can be lost here.
    stale = sorted(set(table) - used)
    if stale:
        print("note: table rows with no bullet in this source:\n  " + "\n  ".join(stale), file=sys.stderr)


def area_header(area: str) -> str:
    title, covers = AREAS[area]
    return (
        f"# Rules: {title}\n\n"
        f"**Covers:** {covers}\n\n"
        "How to use this file: read the contents list, then read only the entries your "
        "change touches (each line gives the line number where the full text starts). "
        "The rules that apply to every change are in the root `CLAUDE.md`. To add a rule, "
        "see \"Adding a rule\" there.\n\n"
        f"{INDEX_START}\n{INDEX_END}\n"
    )


def demote_section(text: str) -> str:
    """A whole `## ` section moved into an area file becomes one bullet-free block."""
    lines = text.rstrip("\n").split("\n")
    lines[0] = "### " + lines[0][3:] + " (the full text from before the split)"
    return "\n".join(lines)


def split(source_path: Path, again: bool = False) -> None:
    # The area files are edited by hand once the split has landed. Writing them
    # again from the old file would throw those edits away, so a second run has
    # to be asked for by name.
    if (RULES_DIR / ARCHIVE_NAME).exists() and not again:
        raise SystemExit(
            f"docs/rules/{ARCHIVE_NAME} already exists: the split was done. Running it again "
            "REWRITES every area file from the old text and drops any rule added since. "
            "Only before the split has landed on master: add --again."
        )
    source = read_lf(source_path)
    segs = parse(source)
    assign(segs)
    write_lf(RULES_DIR / ARCHIVE_NAME, source)

    by_area: dict[str, list[Segment]] = {a: [] for a in AREAS}
    for s in segs:
        if s.dest in by_area:
            by_area[s.dest].append(s)

    for area, items in by_area.items():
        out = [area_header(area)]
        also = [s for s in segs if s.kind == "bullet" and area in s.also]
        if also:
            out.append(ALSO_START)
            out.append("## Also touches this area (the full text is in another file)\n")
            for s in also:
                ver = f" (v{s.version})" if s.version else ""
                out.append(f"- `{s.dest}.md`: **{s.headline}**{ver}")
            out.append(ALSO_END + "\n")
        out.append(RULES_HEADING + "\n")
        for s in items:
            out.append((demote_section(s.text) if s.kind == "section" else s.body) + "\n")
        write_lf(RULES_DIR / f"{area}.md", "\n".join(out))

    write_record(source_path, source, segs)
    verify(segs)
    counts = {a: len(v) for a, v in by_area.items()}
    print("split written:", ", ".join(f"{a}={n}" for a, n in counts.items()))


def write_record(source_path: Path, source: str, segs: list[Segment]) -> None:
    bullets = [s for s in segs if s.kind == "bullet"]
    sections = [s for s in segs if s.kind == "section"]
    sha = hashlib.sha256(source.encode("utf-8")).hexdigest()
    out = [
        f"# Record of the CLAUDE.md split ({SPLIT_DATE})",
        "",
        "This file is the record of what was moved where. It is written by",
        "`scripts/split_agent_rules.py` and is not edited by hand.",
        "",
        "## The source",
        "",
        f"- File: the root `CLAUDE.md` as it stood before the split.",
        f"- Lines: {source.count(chr(10)) + (0 if source.endswith(chr(10)) else 1)}.",
        f"- Size: {len(source.encode('utf-8')):,} bytes (LF line ends).",
        f"- SHA-256 (LF line ends): `{sha}`.",
        f"- Kept unchanged as `docs/rules/{ARCHIVE_NAME}`.",
        "",
        "## Totals",
        "",
        f"- Pieces: {len(segs)} ({len(bullets)} top-level bullets, {len(sections)} other parts).",
        "- Joined in order, the pieces are the source file exactly (checked at split time).",
        "- Each bullet went, unchanged, to exactly one area file. \"Unchanged\" is checked by",
        "  the hash in the table below: the text between a bullet's first line and its last",
        "  non-blank line.",
        "",
        "| Area file | Bullets | Other parts |",
        "|---|---:|---:|",
    ]
    for area in AREAS:
        nb = sum(1 for s in bullets if s.dest == area)
        ns = sum(1 for s in sections if s.dest == area)
        out.append(f"| `{area}.md` | {nb} | {ns} |")
    nroot = sum(1 for s in sections if s.dest == "root")
    out += [
        f"| root `CLAUDE.md` (rewritten short; the old text is only in the archive) | 0 | {nroot} |",
        "",
        "## Parts that are not bullets",
        "",
        "| Old lines | Section | Where it went | SHA-256 (first 12) |",
        "|---|---|---|---|",
    ]
    for s in sections:
        where = (
            "rewritten in the root `CLAUDE.md`; the old text is in the archive"
            if s.dest == "root"
            else f"`{s.dest}.md`: the body unchanged, its `##` heading line turned into a `###` heading"
        )
        out.append(f"| {s.start}-{s.end} | {s.section} | {where} | `{s.sha[:12]}` |")
    out += [
        "",
        "## Every bullet",
        "",
        "\"Also listed in\" means the bullet's headline is listed, as a pointer only, in",
        "that area file's \"Also touches this area\" list.",
        "",
        "| # | Old lines | Went to | Also listed in | SHA-256 (first 12) | Headline |",
        "|---:|---|---|---|---|---|",
    ]
    for n, s in enumerate(bullets, 1):
        head = s.headline.replace("|", "\\|")[:140]
        ver = f" (v{s.version})" if s.version else ""
        also = ", ".join(f"`{a}.md`" for a in s.also) or "-"
        out.append(f"| {n} | {s.start}-{s.end} | `{s.dest}.md` | {also} | `{s.sha[:12]}` | {head}{ver} |")
    write_lf(RULES_DIR / RECORD_NAME, "\n".join(out) + "\n")


def verify(segs: list[Segment] | None = None) -> None:
    """Prove the written files hold every bullet of the archive, once, unchanged."""
    archive = read_lf(RULES_DIR / ARCHIVE_NAME)
    if segs is None:
        segs = parse(archive)
        assign(segs)
    texts = {a: read_lf(RULES_DIR / f"{a}.md") for a in AREAS}
    problems = []
    for s in segs:
        if s.dest == "root":
            continue
        body = demote_section(s.text) if s.kind == "section" else s.body
        hits = {a: t.count(body) for a, t in texts.items()}
        total = sum(hits.values())
        if hits.get(s.dest, 0) != 1 or total != 1:
            problems.append(f"line {s.start} ({s.headline[:70]}): expected once in {s.dest}.md, found {hits}")
    moved = sum(1 for s in segs if s.dest != "root")
    if problems:
        raise SystemExit("verify FAILED:\n  " + "\n  ".join(problems))
    print(f"verify ok: {moved} pieces, each found exactly once, unchanged, in its area file")


def main(argv: list[str]) -> None:
    if len(argv) >= 2 and argv[0] in {"propose", "split"}:
        src = Path(argv[1])
        if argv[0] == "propose":
            propose(parse(read_lf(src)))
        else:
            split(src, again="--again" in argv)
    elif argv[:1] == ["verify"]:
        verify()
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    main(sys.argv[1:])
