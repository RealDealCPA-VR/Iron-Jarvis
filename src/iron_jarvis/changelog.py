"""What changed in each version — read for the Updates page (v1.450.0).

The Handbook (``docs/HANDBOOK.md``) documents every feature under a heading
that names the release it came with ("## Stable or Fresh updates
(v1.405.0)"). Those sections are the manual, and they stay there. The release
NOTES — "what changed in the version I am on" — are a different reading of the
same text: one paragraph per version, made of each section's title and first
sentence. ``docs/CHANGELOG.md`` holds that reading for the newest
``KEEP_VERSIONS`` versions and is GENERATED (``scripts/gen_changelog.py``; a
pin runs it with ``--check``), never edited by hand. The daemon serves one
version's paragraph to the Updates card (``routes/helpdocs.py``,
``GET /updates/changelog?version=``), and the file is in the Guide's bundle
(``guide/corpus.BUNDLED_DOCS``) so a frozen build carries it.

Everything here is pure text work: no I/O, nothing raised for an odd
Handbook — a section whose body cannot be read gives an entry with its title
alone.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

#: How many versions the changelog keeps (the Handbook keeps every section).
KEEP_VERSIONS = 20

#: The first line of the generated file; the route and the pin recognise it.
TITLE = "# What changed in Iron Jarvis"

#: Said under the title: where the file comes from and how to remake it.
LEAD = (
    "*One paragraph per version, made from the Handbook's own sections (each "
    "section's title and first sentence). Generated by "
    "`scripts/gen_changelog.py` from `docs/HANDBOOK.md` — edit the Handbook, "
    "then run the script; this file is never edited by hand. The Handbook "
    "holds the full story of each change; Settings › System › Updates shows "
    "the paragraph for the version you are on.*"
)

_VERSIONED_HEADING = re.compile(r"^## (?P<title>.+?) \((?P<version>v\d+\.\d+\.\d+)\)\s*$")
_ENTRY_HEADING = re.compile(r"^## (?P<version>v\d+\.\d+\.\d+)\s*$")
_SENTENCE_END = re.compile(r"[.!?][\"”’)*]*(\s+)(?=[A-Z*\"“(`])")
_LIST_MARK = re.compile(r"^\s*(?:[-*+]|\d+\.)\s+")
_BOLD_LEAD = re.compile(r"^\*\*[^*]+\*\*[:.]?$")


def version_key(version: str) -> tuple[int, ...]:
    """``"v1.405.0"`` → ``(1, 405, 0)`` (a bad string sorts first)."""
    m = re.match(r"v?(\d+)\.(\d+)\.(\d+)", (version or "").strip())
    return tuple(int(g) for g in m.groups()) if m else (-1,)


def normalize_version(version: str) -> str:
    """``"1.405.0"`` / ``" v1.405.0 "`` → ``"v1.405.0"``; junk → ``""``."""
    m = re.match(r"^\s*v?(\d+\.\d+\.\d+)\s*$", version or "")
    return f"v{m.group(1)}" if m else ""


@dataclass(frozen=True)
class HandbookSection:
    version: str
    title: str
    first_sentence: str


def _paragraphs(body: str) -> list[str]:
    """The prose paragraphs and list items of a section body, in order; a
    sub-heading, a rule, a table, a quote and a fenced block are skipped and
    each list item is its own paragraph."""
    out: list[str] = []
    buf: list[str] = []
    in_fence = False

    def flush() -> None:
        if buf:
            text = " ".join(x.strip() for x in buf)
            out.append(_LIST_MARK.sub("", text, count=1) if _LIST_MARK.match(buf[0]) else text)
            buf.clear()

    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith("```"):
            flush()
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        if not stripped:
            flush()
            continue
        if stripped.startswith(("#", "---", "|", ">")):
            flush()
            continue
        if buf and _LIST_MARK.match(line):
            flush()
        buf.append(line)
    flush()
    return out


def _sentences(text: str) -> list[str]:
    """``text`` cut at every sentence end (a stop, then closing quotes or
    bold markers, then a space before a capital or an opening mark), the
    closing marks kept with their sentence."""
    out: list[str] = []
    at = 0
    for m in _SENTENCE_END.finditer(text):
        out.append(text[at : m.start(1)].strip())
        at = m.end(1)
    out.append(text[at:].strip())
    return [piece for piece in out if piece]


def first_sentence(body: str) -> str:
    """The first sentence of a section's body: the first paragraph that is
    prose or a list item, cut at its first sentence end. A bold lead-in that
    is a sentence on its own ("**Antigravity.**") is kept together with the
    sentence that follows it — in the same paragraph or the next one — so an
    entry never reads as a bare title. Markdown emphasis is kept."""
    sentences: list[str] = []
    for para in _paragraphs(body):
        for piece in _sentences(para):
            sentences.append(piece)
            if not _BOLD_LEAD.match(piece):
                return " ".join(sentences)
            if len(sentences) >= 3:
                return " ".join(sentences)
    return " ".join(sentences)


def handbook_sections(handbook: str) -> list[HandbookSection]:
    """Every ``## <title> (vX.Y.Z)`` section of the Handbook, in file order."""
    out: list[HandbookSection] = []
    current: tuple[str, str] | None = None
    buf: list[str] = []

    def flush() -> None:
        if current is None:
            return
        title, version = current
        out.append(HandbookSection(version, title, first_sentence("\n".join(buf))))

    for line in (handbook or "").replace("\r\n", "\n").split("\n"):
        if line.startswith("## "):
            flush()
            m = _VERSIONED_HEADING.match(line)
            current = (m.group("title").strip(), m.group("version")) if m else None
            buf = []
            continue
        if current is not None:
            buf.append(line)
    flush()
    return out


def generate(handbook: str, *, keep: int = KEEP_VERSIONS) -> str:
    """The whole ``docs/CHANGELOG.md`` text for a Handbook: the newest
    ``keep`` versions that have a section, newest first, one paragraph each
    (a version with several sections gets one sentence per section, in the
    Handbook's order)."""
    by_version: dict[str, list[HandbookSection]] = {}
    for s in handbook_sections(handbook):
        by_version.setdefault(s.version, []).append(s)
    versions = sorted(by_version, key=version_key, reverse=True)[:keep]
    parts = [TITLE, "", LEAD, ""]
    for v in versions:
        pieces = []
        for s in by_version[v]:
            title = s.title.rstrip(".")
            pieces.append(f"**{title}.** {s.first_sentence}".strip())
        parts += [f"## {v}", "", " ".join(pieces), ""]
    return "\n".join(parts).rstrip("\n") + "\n"


@dataclass(frozen=True)
class Entry:
    version: str
    text: str


def entries(changelog: str) -> list[Entry]:
    """The versions a generated changelog holds, in the order written."""
    out: list[Entry] = []
    version: str | None = None
    buf: list[str] = []

    def flush() -> None:
        if version is not None:
            out.append(Entry(version, "\n".join(buf).strip()))

    for line in (changelog or "").replace("\r\n", "\n").split("\n"):
        m = _ENTRY_HEADING.match(line)
        if m:
            flush()
            version = m.group("version")
            buf = []
            continue
        if version is not None:
            buf.append(line)
    flush()
    return out


def lookup(changelog: str, version: str) -> dict:
    """What the Updates card asks for: the entry for ``version`` when there is
    one, else the newest entry below it (a patch release that only moved
    tests has no section of its own) — ``found`` says which. Never raises:
    an unreadable file or an odd version gives ``found: False`` with no
    ``nearest``."""
    want = normalize_version(version)
    rows = entries(changelog or "")
    latest = rows[0].version if rows else ""
    answer: dict = {"version": want, "found": False, "latest": latest, "title": "", "text": ""}
    if not want or not rows:
        return answer
    for e in rows:
        if e.version == want:
            answer.update(found=True, title=f"What changed in {want}", text=e.text)
            return answer
    below = [e for e in rows if version_key(e.version) < version_key(want)]
    if below:
        nearest = max(below, key=lambda e: version_key(e.version))
        answer.update(nearest=nearest.version, title=f"What changed in {nearest.version}", text=nearest.text)
    return answer
