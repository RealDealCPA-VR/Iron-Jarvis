export type OfferKind = "work" | "user" | "";

const cache = new Map<string, RegExp>();
function rx(key: string, extra = ""): RegExp {
  const k = `${key}/${extra}`;
  let r = cache.get(k);
  if (!r) {
    const p = PATTERNS[key];
    r = new RegExp(p.source, p.flags + extra);
    cache.set(k, r);
  }
  return r;
}

/** Python's `\w` is Unicode-aware; this keeps letters of any script. */
const TRAILING_MARKS = /[^\p{L}\p{N}_.?!]+$/u;
const CLOSER = /^(?:thanks|thank\s+you|cheers|enjoy|hope\s+this\s+helps)[.!]*$/i;
const CHOICE_SPLIT = /,?\s+or\s+/i;

/** The reply's last paragraph of PROSE, or "" when it ends in a code block,
 *  a quote or nothing at all. */
function lastParagraph(text: string): string {
  const lines = String(text ?? "").replace(/\r\n/g, "\n").replace(/\r/g, "\n").split("\n");
  let inFence = false;
  let lastFenceClose = -1;
  lines.forEach((line, i) => {
    if (rx("fence").test(line)) {
      inFence = !inFence;
      if (!inFence) lastFenceClose = i;
    }
  });
  if (inFence) return "";
  while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
  if (!lines.length) return "";
  if (lines.length - 1 === lastFenceClose || rx("quote").test(lines[lines.length - 1])) return "";
  const para: string[] = [];
  for (let i = lines.length - 1; i >= 0; i--) {
    const line = lines[i];
    if (!line.trim() || rx("fence").test(line) || rx("quote").test(line)) break;
    para.push(line);
  }
  return para.reverse().join(" ").trim();
}

/** The last sentence of the reply's last paragraph of prose (emphasis, a
 *  list marker and trailing emoji taken off), or "". */
export function lastSentence(text: string): string {
  let para = lastParagraph(text);
  if (!para) return "";
  para = para.replace(rx("leadMark"), "");
  para = para.replace(rx("emphasis", "g"), "");
  para = para.replace(TRAILING_MARKS, "").trim();
  if (!para) return "";
  const sentences = para
    .split(rx("sentenceSplit"))
    .map((s) => s.trim())
    .filter(Boolean);
  if (!sentences.length) return "";
  let last = sentences[sentences.length - 1];
  if (sentences.length > 1 && CLOSER.test(last)) last = sentences[sentences.length - 2];
  return last.replace(rx("leadMark"), "").trim();
}

function actions(sentence: string): string[] {
  const out: string[] = [];
  for (const m of sentence.matchAll(rx("actionLead", "g"))) {
    out.push(sentence.slice((m.index ?? 0) + m[0].length).replace(rx("actionFiller"), "").trim());
  }
  return out;
}

/** Each clause of an offered action, its lead words and a `run …` /
 *  command-line wrapper taken off — the daemon's `_clauses` (v1.407.2). */
function clauses(action: string): string[] {
  const out: string[] = [];
  for (const part of String(action ?? "").split(rx("clauseSplit"))) {
    const c = (part ?? "").trim().replace(rx("clauseLead"), "").replace(rx("actionFiller"), "").trim();
    if (!c) continue;
    out.push(c);
    const inner = c.replace(rx("clauseRun"), "").replace(rx("clauseCmd"), "").trim();
    if (inner && inner !== c) out.push(inner);
  }
  return out;
}

/** Is this offered ACTION the user's to decide — any clause of it? The
 *  daemon's `_owned` (v1.407.2: the knowledge the next-step box used to keep
 *  in its own `asksFirst` list lives in the daemon now). */
const owned = (a: string): boolean =>
  rx("userOwns").test(a) ||
  rx("production").test(a) ||
  clauses(a).some(
    (c) =>
      !rx("clauseNoun").test(c) &&
      (rx("userOwns").test(c) || rx("clauseOwns").test(c) || rx("stagingMigration").test(c)),
  );

/** What the reply's ending offers: "work", "user" (the user's to decide) or
 *  "" — the daemon's `offer_kind`. */
export function offerKind(text: string): OfferKind {
  try {
    const sentence = lastSentence(text);
    if (!sentence || sentence.length > 400) return "";
    if (!(rx("asks").test(sentence) || rx("states").test(sentence) || rx("canIf").test(sentence))) return "";
    if (rx("explain").test(sentence) || rx("vague").test(sentence) || rx("later").test(sentence)) return "";
    const acts = actions(sentence);
    if (acts.some((a) => rx("explainStart").test(a))) return "";
    if (acts.some(owned)) return "user";
    const parts = sentence.split(CHOICE_SPLIT);
    if (parts.length > 1 && !rx("declineAlt").test(parts[parts.length - 1].trim())) return "";
    return "work";
  } catch {
    return "";
  }
}

/** The words of the offered action ("add tests", "send this to the client")
 *  — the user's decision's action when there is one, else the first — or "".
 *  The daemon's `offered_action`. */
export function offeredAction(text: string): string {
  try {
    const kind = offerKind(text);
    if (!kind) return "";
    let acts = actions(lastSentence(text));
    if (kind === "user") {
      const mine = acts.filter(owned);
      if (mine.length) acts = mine;
    }
    for (const a of acts) {
      const end = a.search(rx("actionEnd"));
      let words = (end >= 0 ? a.slice(0, end) : a).trim();
      if (!words) continue;
      if (words.length > OFFER_ACTION_MAX) {
        const cut = words.slice(0, OFFER_ACTION_MAX);
        const sp = cut.lastIndexOf(" ");
        words = (sp >= 0 ? cut.slice(0, sp) : cut).trim();
      }
      return words;
    }
    return "";
  } catch {
    return "";
  }
}
