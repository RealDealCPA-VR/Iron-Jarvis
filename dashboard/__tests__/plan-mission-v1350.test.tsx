/**
 * v1.350.0 re-review: the MISSION screen answers a plan ask like every other
 * surface.
 *
 * The mission screen draws its OWN approval card (components/agents/mission/
 * MissionOutput), not the chat's ApprovalCard, so the integrate step's
 * "ApprovalCard knows approve_plan by name" never reached it: with "Ask me to
 * approve an agent's plan" on, a mission's coordinator (origin job:mission)
 * or a teammate (job:mission-member) parked on its plan showed "Jarvis wants
 * to use approve plan" and offered "Allow for this task", a run-wide answer
 * the Handbook says a plan never has, with no plan to read. The teammate's
 * card said "Waiting for your OK to use approve plan."
 *
 * Plain words: the mission card now says the agent wants you to approve its
 * plan, shows the plan's steps (the daemon's own copy, every step waiting
 * while the ask is out), and offers only Allow once and Decline.
 *
 * The plan body is the REAL daemon's (fixtures/plan-contract-v1350.json,
 * `allow.plan_awaiting`, generated by tests/test_plan_contract_v1350.py).
 * Only the transport (lib/api) and next/link are mocked; MissionOutput,
 * AgentCards and readSessionPlan are the real ones.
 */

import { readFileSync } from "node:fs";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { cleanup, fireEvent, render, screen, waitFor, within } from "@testing-library/react";

const H = vi.hoisted(() => ({
  gets: [] as string[],
  getResponses: {} as Record<string, unknown>,
  posts: [] as Array<{ path: string; body: unknown }>,
}));

vi.mock("@/lib/api", () => {
  class ApiError extends Error {
    status: number;
    cancelled = false;
    constructor(message: string, status = 500) {
      super(message);
      this.status = status;
      this.name = "ApiError";
    }
  }
  return {
    ApiError,
    API_BASE: "",
    ijToken: () => "",
    sseUrl: (p: string) => p,
    get: (p: string) => {
      H.gets.push(p);
      const r = H.getResponses[p];
      if (r === undefined) return Promise.reject(new ApiError(`unmocked GET ${p}`, 404));
      return Promise.resolve(JSON.parse(JSON.stringify(r)));
    },
    post: (p: string, body?: unknown) => {
      H.posts.push({ path: p, body });
      return Promise.resolve({});
    },
    put: () => Promise.resolve({}),
    del: () => Promise.resolve({}),
    patch: () => Promise.resolve({}),
  };
});

vi.mock("next/link", () => ({
  default: ({ children, href, ...rest }: React.ComponentProps<"a">) => (
    <a href={href} {...rest}>
      {children}
    </a>
  ),
}));

import { AgentCards } from "@/components/agents/mission/AgentCards";
import { MissionOutput } from "@/components/agents/mission/MissionOutput";
import type { MissionMember, MissionView } from "@/lib/mission";
import type { MissionLive, MissionLiveStore } from "@/lib/useMission";

const FIXTURE = JSON.parse(
  readFileSync(path.join(__dirname, "fixtures", "plan-contract-v1350.json"), "utf8").replace(/\r\n/g, "\n"),
) as {
  goals: string[];
  allow: { plan_awaiting: { run_id: string; steps: { goal: string; state: string }[] } };
};
const GOALS = FIXTURE.goals;
const AWAITING = FIXTURE.allow.plan_awaiting;

function member(over: Partial<MissionMember> = {}): MissionMember {
  return {
    session_id: "c2",
    agent: "custom:writer",
    name: "writer",
    kind: "custom",
    task: "draft the strategy",
    status: "waiting_you",
    progress: { pct: null, label: "", basis: "steps" },
    activity: "",
    waiting_on: null,
    steps: 0,
    result: "",
    files: [],
    started_at: null,
    finished_at: null,
    provider: "fleet-custom",
    model: "glm",
    ...over,
  };
}

function view(extra: Partial<MissionView> = {}): MissionView {
  return {
    session: {
      id: "s1",
      task: "write a market report",
      objective: "write a market report",
      status: "active",
      outcome: null,
      project_id: null,
      created_at: null,
      finished_at: null,
      interrupted: false,
      continued_as: null,
      provider: "",
      model: "",
      route_note: "",
    },
    coordinator: { name: "Jarvis", status: "working", waiting_on: null, steps: 0 },
    members: [],
    progress: { done: 0, total: 0 },
    activity: [],
    deliverable: { text: "", documents: [], worklist: null },
    ...extra,
  };
}

const EMPTY: MissionLive = { coordinator: "", coordinatorPhase: "", coordinatorNarration: "", members: {}, latest: null };
const liveStore: MissionLiveStore = { get: () => EMPTY, subscribe: () => () => {} };

function renderOutput(v: MissionView) {
  return render(<MissionOutput view={v} liveStore={liveStore} objective="" onChanged={() => {}} onOpen={() => {}} />);
}

const buttonNames = (el: HTMLElement) => within(el).getAllByRole("button").map((b) => b.textContent?.trim());

beforeEach(() => {
  H.gets = [];
  H.posts = [];
  H.getResponses = {};
});
afterEach(cleanup);

describe("the mission screen's card for a plan ask", () => {
  it("the coordinator's plan: its words, its steps from the daemon, Allow once and Decline only", async () => {
    H.getResponses["/sessions/s1/plan"] = AWAITING;
    renderOutput(view({ coordinator: { name: "Jarvis", status: "waiting_you", waiting_on: { approval_id: "ask-1", tool: "approve_plan" }, steps: 0 } }));
    const card = await screen.findByTestId("mission-approval");
    expect(card.textContent).toContain("Jarvis wants you to approve its plan");
    expect(card.textContent).not.toContain("approve plan."); // never the tool id as words
    expect(card.textContent).not.toContain("wants to use");
    // The plan itself, numbered, read from the daemon's copy of THIS session.
    const list = await within(card).findByTestId("mission-approval-plan");
    expect(within(list).getAllByRole("listitem").map((li) => li.textContent)).toEqual(GOALS);
    expect(list.tagName).toBe("OL");
    expect(H.gets).toEqual(["/sessions/s1/plan"]);
    // Approved once or declined: nothing run-wide.
    expect(buttonNames(card)).toEqual(["Allow once", "Decline"]);
    fireEvent.click(within(card).getByText("Allow once"));
    await waitFor(() => expect(H.posts).toEqual([{ path: "/chat/approvals/ask-1", body: { decision: "once" } }]));
  });

  it("a teammate's plan reads the TEAMMATE's session, and Decline sends deny", async () => {
    H.getResponses["/sessions/c2/plan"] = AWAITING;
    renderOutput(view({ members: [member({ waiting_on: { approval_id: "ask-2", tool: "approve_plan" } })] }));
    const card = await screen.findByTestId("mission-approval");
    expect(card.textContent).toContain("writer wants you to approve its plan");
    const list = await within(card).findByTestId("mission-approval-plan");
    expect(within(list).getAllByRole("listitem").map((li) => li.textContent)).toEqual(GOALS);
    expect(H.gets).toEqual(["/sessions/c2/plan"]);
    expect(buttonNames(card)).toEqual(["Allow once", "Decline"]);
    fireEvent.click(within(card).getByText("Decline"));
    await waitFor(() => expect(H.posts).toEqual([{ path: "/chat/approvals/ask-2", body: { decision: "deny" } }]));
  });

  it("no daemon copy (a 404): the plan words and the two answers still, no list, no error", async () => {
    renderOutput(view({ coordinator: { name: "Jarvis", status: "waiting_you", waiting_on: { approval_id: "ask-1", tool: "approve_plan" }, steps: 0 } }));
    const card = await screen.findByTestId("mission-approval");
    await waitFor(() => expect(H.gets).toEqual(["/sessions/s1/plan"]));
    expect(card.textContent).toContain("Jarvis wants you to approve its plan");
    expect(within(card).queryByTestId("mission-approval-plan")).toBeNull();
    expect(buttonNames(card)).toEqual(["Allow once", "Decline"]);
  });

  it("control: any other ask is exactly as before (its tool's name, Allow for this task, no plan read)", async () => {
    renderOutput(view({ coordinator: { name: "Jarvis", status: "waiting_you", waiting_on: { approval_id: "ask-3", tool: "write_file" }, steps: 0 } }));
    const card = await screen.findByTestId("mission-approval");
    expect(card.textContent).toContain("Jarvis wants to use write file");
    expect(buttonNames(card)).toEqual(["Allow once", "Allow for this task", "Decline"]);
    fireEvent.click(within(card).getByText("Allow for this task"));
    await waitFor(() => expect(H.posts).toEqual([{ path: "/chat/approvals/ask-3", body: { decision: "conversation" } }]));
    expect(H.gets).toEqual([]);
    expect(within(card).queryByTestId("mission-approval-plan")).toBeNull();
  });
});

describe("the teammate's card on the mission screen", () => {
  it("says it is waiting for you to approve its plan, never 'to use approve plan'", () => {
    render(<AgentCards members={[member({ waiting_on: { approval_id: "ask-2", tool: "approve_plan" } })]} />);
    fireEvent.click(within(screen.getByTestId("mission-card-custom:writer")).getAllByRole("button")[0]);
    const detail = screen.getByTestId("mission-card-detail-custom:writer");
    expect(detail.textContent).toContain("Waiting for you to approve its plan.");
    expect(detail.textContent).not.toContain("approve plan.");
  });

  it("control: any other ask keeps its tool's words", () => {
    render(<AgentCards members={[member({ waiting_on: { approval_id: "ask-4", tool: "write_file" } })]} />);
    fireEvent.click(within(screen.getByTestId("mission-card-custom:writer")).getAllByRole("button")[0]);
    expect(screen.getByTestId("mission-card-detail-custom:writer").textContent).toContain(
      "Waiting for your OK to use write file.",
    );
  });
});
